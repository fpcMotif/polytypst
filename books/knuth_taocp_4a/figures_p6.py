def _draw_genjiko_clean(
    c: SvgCanvas,
    x: float,
    y: float,
    blocks: list[list[int]],
    n: int,
    w: float,
    h: float,
    sw: float = 1.35,
) -> None:
    step = w / max(1, n - 1)
    xs = [x + (i - 1) * step for i in range(1, n + 1)]
    multi = sorted(
        [sorted(b) for b in blocks if len(b) >= 2], key=lambda b: (b[-1] - b[0], b[0])
    )
    levels: list[int] = []
    spans: list[tuple[int, int, int]] = []
    for b in multi:
        lo, hi = b[0], b[-1]
        lvl = 0
        for slo, shi, slvl in spans:
            if not (hi < slo or lo > shi) and slvl >= lvl:
                lvl = slvl + 1
