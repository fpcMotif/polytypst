def _radial_text(
    c: SvgCanvas,
    cx: float,
    cy: float,
    r_inner: float,
    r_outer: float,
    angle_deg: float,
    label: str,
    font_size: float,
    fill: str,
    italic: bool = False,
) -> None:
    rad = math.radians(angle_deg)
    rm = 0.5 * (r_inner + r_outer)
    tx = cx + rm * math.cos(rad)
    ty = cy + rm * math.sin(rad)
    norm_deg = ((angle_deg + 180.0) % 360.0) - 180.0
    rot = norm_deg + 180.0 if (norm_deg > 90.0 or norm_deg < -90.0) else norm_deg
    c.text(tx, ty, label, font_size=font_size, fill=fill, italic=italic, rotate=rot)


