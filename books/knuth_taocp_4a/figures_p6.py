def _parse_forest(parens: str) -> list[tuple[int, list]]:
    idx = 0
    n = len(parens)

    def parse_seq() -> list[tuple[int, list]]:
        nonlocal idx
        nodes = []
        while idx < n and parens[idx] == "(":
            idx += 1
            ch = parse_seq()
            idx += 1
            nodes.append((0, ch))
        return nodes

    return parse_seq()


def _forest_width_units(trees: list[tuple[int, list]]) -> float:
    def tree_w(t: tuple[int, list]) -> float:
        _, ch = t
        if not ch:
            return 1.0
        return max(1.0, sum(tree_w(sub) for sub in ch))

    return sum(tree_w(t) for t in trees) + 0.35 * max(0, len(trees) - 1)


def _draw_mini_forest(
    c: SvgCanvas,
    parens: str,
    x0: float,
    y_top: float,
    dx: float = 6.2,
    dy: float = 6.8,
    r: float = 1.85,
) -> float:
    trees = _parse_forest(parens)
    pal = (
        [c.theme.gold, c.theme.cyan, c.theme.mint, c.theme.violet]
        if c.theme.is_dark
        else [c.theme.fg]
    )

    def tree_w(t: tuple[int, list]) -> float:
        _, ch = t
        if not ch:
            return 1.0
        return max(1.0, sum(tree_w(sub) for sub in ch))

    edges: list[tuple[float, float, float, float, int]] = []
    pts: list[tuple[float, float, int]] = []

    def layout_tree(
        t: tuple[int, list], left_u: float, depth: int
    ) -> tuple[float, float]:
        _, ch = t
        w_u = tree_w(t)
        cx = x0 + (left_u + 0.5 * w_u) * dx
        cy = y_top + depth * dy
        pts.append((cx, cy, depth))
        cur = left_u
        for sub in ch:
            sw = tree_w(sub)
            scx, scy = layout_tree(sub, cur, depth + 1)
            edges.append((cx, cy, scx, scy, depth))
            cur += sw
        return cx, cy

    cur_u = 0.0
    for ti, tr in enumerate(trees):
        if ti > 0:
            cur_u += 0.35
        layout_tree(tr, cur_u, 0)
        cur_u += tree_w(tr)

    edge_col = c.theme.muted if c.theme.is_dark else c.theme.fg
    for x1, y1, x2, y2, _ in edges:
        c.line(x1, y1, x2, y2, stroke=edge_col, stroke_width=1.05)
    for px, py, depth in pts:
        st = pal[depth % len(pal)]
        c.circle(px, py, r, fill=c.theme.bg, stroke=st, stroke_width=1.15)
    return cur_u * dx


def _mirror_parens(p: str) -> str:
    return "".join("(" if ch == ")" else ")" for ch in reversed(p))


def _transpose_parens(p: str) -> str:
    if not p:
        return ""
    depth = 0
    split_at = 0
    for i, ch in enumerate(p):
        depth += 1 if ch == "(" else -1
        if depth == 0:
            split_at = i
            break
    inside = p[1:split_at]
    rest = p[split_at + 1 :]
    return "(" + _transpose_parens(rest) + ")" + _transpose_parens(inside)


