def resolve_inline_symbol(filename: str) -> tuple[str, str] | None:
    """Return (typst_markup, latex_markup) if filename is a known inline symbol/equation."""
    name = filename.split("/")[-1]
    if name in EXACT_SYMBOL_MAP:
        return EXACT_SYMBOL_MAP[name]

    # Pattern fallback for simple fractions like "NbyM.jpg"
    m_frac = re.fullmatch(r"(\d+)by(\d+)\.jpg", name)
    if m_frac:
        a, b = m_frac.groups()
        return (f"${a}/{b}$", rf"\ensuremath{{\tfrac{{{a}}}{{{b}}}}}")

    return None
