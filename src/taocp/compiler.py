class TaocpBookCompiler:
    """Assembles and compiles the complete TAOCP Volume 3 Typst and LaTeX books."""

    def __init__(self, out_dir: Path) -> None:
        self.out_dir = out_dir
        self.out_dir.mkdir(parents=True, exist_ok=True)
        self.typ_path = out_dir / "taocp_vol3.typ"
        self.pdf_path = out_dir / "taocp_vol3.pdf"
        self.tex_path = out_dir / "taocp_vol3.tex"

    def write_sources(self, sections: list[SpineSection]) -> tuple[Path, Path]:
        """Write complete Typst (.typ) and XeLaTeX (.tex) master files."""
        typ_chunks: list[str] = [TYPST_PREAMBLE]
        tex_chunks: list[str] = [LATEX_PREAMBLE]

        toc_inserted = False
        for sec in sections:
            if sec.href == "ch05.html" and not toc_inserted:
                typ_chunks.append(
                    "#pagebreak(weak: true)\n"
                    "#metadata(none)<page_xiv>\n"
                    "#outline(title: [Contents], depth: 3, indent: 1.2em)\n"
                )
                tex_chunks.append(
                    "\\cleardoublepage\n\\hypertarget{page_xiv}{}\n\\tableofcontents\n"
                )
                toc_inserted = True

            if sec.href in PAGEBREAK_HREFS:
                typ_chunks.append("#pagebreak(weak: true)")
                tex_chunks.append("\\clearpage")

            typ_chunks.append(f"// --- Section: {sec.href} ({sec.title}) ---")
            typ_chunks.append(sec.typst_source)

            tex_chunks.append(f"% --- Section: {sec.href} ({sec.title}) ---")
            tex_chunks.append(sec.latex_source)

        tex_chunks.append("\n\\end{document}\n")

        self.typ_path.write_text("\n\n".join(typ_chunks) + "\n", encoding="utf-8")
        self.tex_path.write_text("\n\n".join(tex_chunks) + "\n", encoding="utf-8")
        return self.typ_path, self.tex_path

    def compile_typst_pdf(self) -> Path:
        """Compile taocp_vol3.typ into taocp_vol3.pdf."""
        typst_bin = shutil.which("typst")
        if typst_bin is not None:
            cmd = [typst_bin, "compile", str(self.typ_path), str(self.pdf_path)]
        else:
            cmd = [
                "nix",
                "shell",
                "nixpkgs#typst",
                "--command",
                "typst",
                "compile",
                str(self.typ_path),
                str(self.pdf_path),
            ]
        subprocess.run(cmd, check=True)
        return self.pdf_path
