def _callout(
    target: tuple[float, float],
    text_at: tuple[float, float],
    lines: list[str],
    px_per: tuple[float, float],
    line_h: float = 13.0,
    fontsize: float = 9.5,
    align: Literal["start", "middle", "end"] = "middle",
) -> list[Annotation]:
    kx, ky = px_per
    dx_px = (text_at[0] - target[0]) * kx
    dy_px = (target[1] - text_at[1]) * ky
    below = dy_px > 0
    arrow_idx = 0 if below else len(lines) - 1
    out: list[Annotation] = []
    for i, text in enumerate(lines):
        shift = (i - arrow_idx) * line_h
        out.append(
            Annotation(
                target[0], target[1], text,
                dx=dx_px / 0.6, dy=(dy_px + shift) / 0.6,
                arrow=i == arrow_idx, fontsize=fontsize, align=align,
            )
        )
    return out


