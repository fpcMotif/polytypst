def _interp(knots: list[tuple[float, float]], xs: list[float]) -> list[float]:
    out: list[float] = []
    for x in xs:
        if x <= knots[0][0]:
            out.append(knots[0][1])
            continue
        for (x0, y0), (x1, y1) in pairwise(knots):
            if x0 <= x <= x1:
                out.append(y0 + (x - x0) / (x1 - x0) * (y1 - y0))
                break
        else:
            out.append(knots[-1][1])
    return out


