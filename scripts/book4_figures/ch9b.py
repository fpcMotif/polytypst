def _expand(anchors: Sequence[tuple[float, float]], xs: Sequence[float]) -> list[float]:
    """Linear interpolation between read-off anchor points, evaluated at xs."""
    out: list[float] = []
    for xv in xs:
        if xv <= anchors[0][0]:
            out.append(anchors[0][1])
            continue
        for (x0, y0), (x1, y1) in pairwise(anchors):
            if x0 <= xv <= x1:
                out.append(round(y0 + (y1 - y0) * (xv - x0) / (x1 - x0), 2))
                break
        else:
            out.append(anchors[-1][1])
    return out


