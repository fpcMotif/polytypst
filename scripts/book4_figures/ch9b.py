def _months(anchors: Sequence[tuple[float, float]], start: float, first: int, last: int) -> tuple[list[float], list[float]]:
    """Monthly series from (month index, value) anchors; month 0 is `start`."""
    idx = list(range(first, last + 1))
    return [start + m / 12 for m in idx], _expand(anchors, idx)


