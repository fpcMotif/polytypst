def _signed_stack(components: Sequence[Sequence[float]]) -> list[list[float]]:
    """Bottoms for bars stacked upward from zero when positive and downward when negative."""
    n = len(components[0])
    up = [0.0] * n
    down = [0.0] * n
    bottoms: list[list[float]] = []
    for comp in components:
        b: list[float] = []
        for i, v in enumerate(comp):
            if v >= 0:
                b.append(up[i])
                up[i] += v
            else:
                b.append(down[i])
                down[i] += v
        bottoms.append(b)
    return bottoms


