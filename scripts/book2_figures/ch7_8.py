def _daily_series(
    n_steps: int,
    segments: list[tuple[float, float, float, float]],
    spikes: list[tuple[float, float]],
    seed: int,
    flip: bool = False,
    per_step: int = 8,
) -> tuple[list[float], list[float]]:
    rng = random.Random(seed)
    xs = [i / per_step for i in range(n_steps * per_step + 1)]
    ys: list[float] = []
    for x in xs:
        lo, hi = next(((s[2], s[3]) for s in segments if s[0] <= x <= s[1]), (segments[-1][2], segments[-1][3]))
        ys.append(rng.choice((lo, hi)) if flip else rng.uniform(lo, hi))
    for x, v in spikes:
        ys[round(x * per_step)] = v
    return xs, ys


def _rate_panel(
    title: str,
    labels: list[str],
    label_step: int,
    ylim: tuple[float, float],
    ystep: float,
    avg_label: str,
    policy_label: str,
    policy: list[tuple[float, float, float]],
    avg: tuple[list[float], list[float]],
    high: tuple[list[float], list[float]],
    low: tuple[list[float], list[float]],
) -> PanelSpec:
    n_ticks = round((ylim[1] - ylim[0]) / ystep) + 1
    policy_x: list[float] = []
    policy_y: list[float] = []
    for x0, x1, v in policy:
        policy_x += [x0, x1]
        policy_y += [v, v]
    return PanelSpec(
        title=title,
        xlim=(0.0, float(len(labels) - 1)),
        ylim=ylim,
        xticks=[(float(i), lab) for i, lab in enumerate(labels) if i % label_step == 0],
        yticks=_ticks([round(ylim[0] + ystep * k, 6) for k in range(n_ticks)], "g"),
        ylabel="%",
        zero_line=False,
        legend_loc="bottom",
        lines=[
            LineSeries(x=avg[0], y=avg[1], label=avg_label, color_idx=0, width=1.4),
            LineSeries(x=policy_x, y=policy_y, label=policy_label, color_idx=0, width=3.4),
            LineSeries(x=high[0], y=high[1], label="最高值", color_idx=5, width=1.2),
            LineSeries(x=low[0], y=low[1], label="最低值", color_idx=0, style="dotted", width=1.4),
        ],
    )


