def _ticks(vals: list[float], fmt: str) -> list[tuple[float, str]]:
    return [(v, format(v, fmt)) for v in vals]


def _interp(knots: list[tuple[float, float]], xs: list[float]) -> list[float]:
    out: list[float] = []
    for x in xs:
        if x <= knots[0][0]:
            out.append(knots[0][1])
            continue
        if x >= knots[-1][0]:
            out.append(knots[-1][1])
            continue
        for i in range(len(knots) - 1):
            x0, y0 = knots[i]
            x1, y1 = knots[i + 1]
            if x0 <= x <= x1:
                t = (x - x0) / (x1 - x0) if x1 > x0 else 0.0
                out.append(y0 + t * (y1 - y0))
                break
    return out


def _irf_panel(
    title: str,
    mid: list[tuple[float, float]],
    upper: list[tuple[float, float]],
    lower: list[tuple[float, float]],
    ylim: tuple[float, float],
    yticks: list[tuple[float, str]],
    tick_step: int = 5,
) -> PanelSpec:
    xs = [float(m) for m in range(1, 25)]
    ys = _interp(mid, xs)
    high = _interp(upper, xs)
    low = _interp(lower, xs)
    return PanelSpec(
        title=title,
        xlim=(1.0, 24.0),
        ylim=ylim,
        xticks=[(float(h), str(h)) for h in range(tick_step, 25, tick_step)],
        yticks=yticks,
        zero_line=True,
        legend_loc="none",
        bands=[
            BandSeries(
                x=xs,
                y_low=low,
                y_high=high,
                color_idx=0,
                show_edges=True,
                edge_style="dashed",
            )
        ],
        lines=[
            LineSeries(
                x=xs,
                y=ys,
                color_idx=0,
                style="solid",
                width=2.2,
            )
        ],
    )


