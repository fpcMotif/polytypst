def _gapped_series(clusters: list[list[tuple[float, float]]]) -> tuple[list[float], list[float | None]]:
    xs: list[float] = []
    ys: list[float | None] = []
    for cluster in clusters:
        points = cluster if len(cluster) > 1 else cluster * 2
        for x, y in points:
            xs.append(x)
            ys.append(y)
        xs.append(points[-1][0])
        ys.append(None)
    return xs, ys


