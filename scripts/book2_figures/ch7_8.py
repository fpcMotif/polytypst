def _boxed_notes(
    notes: list[tuple[float, float, list[str], tuple[float, float] | None]],
    px_per_x: float,
    px_per_y: float,
    fontsize: float = 8.5,
) -> list[Annotation]:
    line_h = fontsize + 2.0
    out: list[Annotation] = []
    for x_text, y_text, lines, target in notes:
        tx, ty = target if target else (x_text, y_text + 40.0 / px_per_y)
        arrow_line = len(lines) - 1 if target and ty < y_text else 0
        for i, text in enumerate(lines):
            dx = (x_text - tx) * px_per_x / PRINT_SCALE
            baseline = (ty - y_text) * px_per_y + line_h * (i + 1)
            dy = (baseline - 11.0 if baseline > 11.0 else min(baseline + 4.0, 0.0)) / PRINT_SCALE
            out.append(
                Annotation(
                    x=tx,
                    y=ty,
                    text=text,
                    dx=dx,
                    dy=dy,
                    arrow=target is not None and i == arrow_line,
                    color_idx=0,
                    fontsize=fontsize,
                    align="start",
                )
            )
    return out


