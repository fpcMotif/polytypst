def _xs(knots: list[tuple[float, float]]) -> list[float]:
    return [k[0] for k in knots]


def _ys(knots: list[tuple[float, float]]) -> list[float]:
    return [k[1] for k in knots]


def _stepped(start: float, step: float, values: list[float]) -> list[tuple[float, float]]:
    return [(start + step * i, v) for i, v in enumerate(values)]


def _quarterly(start: float, values: list[float]) -> list[tuple[float, float]]:
    return _stepped(start, 0.25, values)


