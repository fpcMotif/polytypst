def _interleave_none(xs: list[float], ys: list[float]) -> tuple[list[float], list[float | None]]:
    out_x: list[float] = []
    out_y: list[float | None] = []
    for xv, yv in zip(xs, ys):
        out_x.append(xv)
        out_y.append(yv)
        out_x.append(xv)
        out_y.append(None)
    return out_x, out_y


