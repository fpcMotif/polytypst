def _neg(v: float) -> str:
    return f"{v:g}".replace("-", "−")


def _xy(pairs: list[tuple[float, float]]) -> tuple[list[float], list[float]]:
    return [p[0] for p in pairs], [p[1] for p in pairs]


def _quarters(start: float, n: int) -> list[float]:
    return [start + 0.25 * i for i in range(n)]


def _year_span_ticks(first: int, last: int, step: int = 1) -> list[tuple[float, str]]:
    return [(y + 0.5, str(y)) for y in range(first, last + 1, step)]


def _irf_panel(
    title: str,
    ylim: tuple[float, float],
    yticks: list[float],
    real: list[tuple[float, float]],
    inflation: list[tuple[float, float]],
) -> PanelSpec:
    rx, ry = _xy(real)
    ix, iy = _xy(inflation)
    return PanelSpec(
        title=title,
        xlim=(0.0, 104.0),
        ylim=ylim,
        xticks=[float(v) for v in range(0, 97, 8)],
        yticks=[(v, _neg(v)) for v in yticks],
        lines=[
            LineSeries(x=rx, y=ry, label="实际利率", color_idx=0, width=1.8, fixed_style=True),
            LineSeries(x=ix, y=iy, label="通货膨胀变动", color_idx=0, style="dotted", width=1.5, fixed_style=True),
        ],
        legend_loc="top",
    )


