def _years(first: int, last: int) -> list[float]:
    return [float(y) for y in range(first, last + 1)]


def _text_w(text: str, size: float) -> float:
    return sum(size if ord(ch) > 0x2E7F else size * 0.56 for ch in text)


def _svg_open(w: float, h: float, title: str, mode: ThemeMode) -> list[str]:
    pal = get_palette(mode)
    return [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:.0f} {h:.0f}" width="{w:.0f}" height="{h:.0f}">',
        f"<title>{escape(title)}</title>",
        f'<rect width="{w:.0f}" height="{h:.0f}" fill="{pal.bg}"/>',
    ]


def _text(
    x: float, y: float, s: str, fill: str, size: float = 10.5, anchor: str = "middle", font: str = FONT_STACK
) -> str:
    return (
        f'<text x="{x:.2f}" y="{y:.2f}" text-anchor="{anchor}" font-family="{font}" font-size="{size}" '
        f'fill="{fill}">{escape(s)}</text>'
    )


def _marker(kind: str, x: float, y: float, color: str, fill: str, r: float = 3.2) -> str:
    if kind == "circle":
        return f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{r:.2f}" fill="{fill}" stroke="{color}" stroke-width="1.2"/>'
    if kind == "square":
        s = r * 0.9
        return (
            f'<rect x="{x - s:.2f}" y="{y - s:.2f}" width="{2 * s:.2f}" height="{2 * s:.2f}" fill="{fill}" '
            f'stroke="{color}" stroke-width="1.0"/>'
        )
    s = r * 1.15
    pts = f"{x:.2f},{y - s:.2f} {x - s:.2f},{y + s * 0.85:.2f} {x + s:.2f},{y + s * 0.85:.2f}"
    return f'<polygon points="{pts}" fill="{fill}" stroke="{color}" stroke-width="1.0"/>'


def _path_d(pts: Sequence[tuple[float, float]], dash: str) -> str:
    """Dashes are cut into the path itself because pymupdf's SVG reader ignores stroke-dasharray."""
    if dash == "solid":
        return "M " + " L ".join(f"{x:.2f},{y:.2f}" for x, y in pts)
    on, off = DASHES[dash]
    out: list[str] = []
    left, draw = on, True
    (x, y) = pts[0]
    out.append(f"M {x:.2f},{y:.2f}")
    for nx, ny in pts[1:]:
        seg = math.hypot(nx - x, ny - y)
        if seg < 1e-6:
            continue
        ux, uy = (nx - x) / seg, (ny - y) / seg
        while seg > 1e-6:
            step = min(seg, left)
            x, y, seg, left = x + ux * step, y + uy * step, seg - step, left - step
            if draw:
                out.append(f"L {x:.2f},{y:.2f}")
            if left <= 1e-6:
                draw = not draw
                left = on if draw else off
                if draw:
                    out.append(f"M {x:.2f},{y:.2f}")
    return " ".join(out)


def _y_axis(
    out: list[str], px0: float, px1: float, map_y: Callable[[float], float], ticks: Sequence[float], mode: ThemeMode
) -> None:
    pal = get_palette(mode)
    for v in ticks:
        yy = map_y(v)
        out.append(
            f'<line x1="{px0:.2f}" y1="{yy:.2f}" x2="{px1:.2f}" y2="{yy:.2f}" stroke="{pal.grid}" '
            'stroke-width="0.9" stroke-dasharray="2.5,2.5"/>'
        )
        out.append(f'<line x1="{px0:.2f}" y1="{yy:.2f}" x2="{px0 + 4.5:.2f}" y2="{yy:.2f}" stroke="{pal.axis}" stroke-width="1.1"/>')
        out.append(_text(px0 - 6.5, yy + 3.8, f"{v:g}", pal.muted, anchor="end", font=SANS_STACK))


def _legend(out: list[str], items: Sequence[tuple[str, str, str, str, str | None, bool]], cx: float, y: float, mode: ThemeMode) -> None:
    """Items are (label, kind, colour, dash, marker, hollow); kind "bar" draws a swatch filled with the colour."""
    pal = get_palette(mode)
    widths = [22.0 + _text_w(label, 10.8) + 14.0 for label, *_ in items]
    x = cx - sum(widths) / 2
    for (label, kind, color, dash, marker, hollow), w in zip(items, widths):
        if kind == "bar":
            out.append(f'<rect x="{x:.2f}" y="{y - 8.5:.2f}" width="14" height="9" fill="{color}" stroke="{pal.fg}" stroke-width="0.8"/>')
        else:
            d = _path_d([(x, y - 4), (x + 18, y - 4)], dash)
            out.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="1.6"/>')
            if marker:
                out.append(_marker(marker, x + 9, y - 4, color, pal.bg if hollow else color, 3.0))
        out.append(_text(x + 22, y, label, pal.fg, 10.8, "start"))
        x += w


