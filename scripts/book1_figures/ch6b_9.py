def _vertical_text(x: float, y_mid: float, text: str, color: str, size: float = 11.0) -> str:
    step = size * 1.08
    y0 = y_mid - step * (len(text) - 1) / 2
    return "".join(
        f'<text x="{x:.1f}" y="{y0 + step * i + size * 0.36:.1f}" text-anchor="middle" font-family="{FONT_STACK}" '
        f'font-size="{size}" fill="{color}">{escape(ch)}</text>'
        for i, ch in enumerate(text)
    )


