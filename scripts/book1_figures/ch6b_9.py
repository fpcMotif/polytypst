def _fdi_panel(
    title: str,
    ylim: tuple[float, float],
    stacks: Sequence[tuple[float, float, float, float, float, float]],
    neg_europe: dict[int, float],
) -> PanelSpec:
    """Each stack is (bar bottom, 美国 top, 欧洲4国 top, 日本 top, 其他 top, 全球总计); neg_europe draws 欧洲4国 below zero."""
    years = [float(y) for y in range(1981, 2006)]
    segments: dict[str, tuple[list[float], list[float]]] = {name: ([], []) for name in ("us", "eu", "jp", "other")}
    for year, (base, us, eu, jp, top, _) in zip(range(1981, 2006), stacks):
        for name, lo, hi in (("us", base, us), ("eu", us, eu), ("jp", eu, jp), ("other", jp, top)):
            if name == "eu" and year in neg_europe:
                lo, hi = neg_europe[year], 0.0
            segments[name][0].append(lo)
            segments[name][1].append(hi - lo)
    labels = {"other": ("其他", 0), "jp": ("日本", 1), "eu": ("欧洲4国", 3), "us": ("美国", 4)}
    return PanelSpec(
        title=title,
        xlim=(1980.4, 2005.6),
        ylim=ylim,
        xticks=[float(y) for y in range(1981, 2006, 2)],
        yticks=[(v, "0" if v == 0 else _signed(v)) for v in [float(t) for t in range(int(ylim[0]), int(ylim[1]) + 1)]],
        xlabel="年",
        zero_line=False,
        hlines=[(0.0, "", "solid")],
        bars=[
            BarSeries(x=years, y=segments[key][1], bottom=segments[key][0], label=labels[key][0], color_idx=labels[key][1], width=1.0, opacity=1.0)
            for key in ("other", "jp", "eu", "us")
        ],
        lines=[LineSeries(x=years, y=[s[5] for s in stacks], label="全球总计", color_idx=0, width=1.2)],
        legend_loc="bottom",
    )


