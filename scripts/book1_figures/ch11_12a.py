def _neg(v: float, fmt: str = "{:g}") -> tuple[float, str]:
    return (v, fmt.format(v).replace("-", "−"))


def _scan_series(
    pts: Sequence[tuple[float, float]], px0: float, x0: float, px_per_x: float
) -> tuple[list[float], list[float | None]]:
    """Points read off the scan as (pixel x, value); convert pixel x to data x."""
    return [x0 + (px - px0) / px_per_x for px, _ in pts], [v for _, v in pts]


def _smooth(xs: Sequence[float], ys: Sequence[float], n: int = 8) -> tuple[list[float], list[float | None]]:
    """Catmull-Rom points between curve readings, so model curves print without corners."""
    out_x: list[float] = []
    out_y: list[float | None] = []
    for i in range(len(xs) - 1):
        p0, p1, p2 = ys[max(i - 1, 0)], ys[i], ys[i + 1]
        p3 = ys[min(i + 2, len(ys) - 1)]
        for k in range(n):
            t = k / n
            out_x.append(xs[i] + (xs[i + 1] - xs[i]) * t)
            out_y.append(
                0.5 * (2 * p1 + (p2 - p0) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t * t
                       + (3 * p1 - p0 - 3 * p2 + p3) * t ** 3)
            )
    out_x.append(xs[-1])
    out_y.append(ys[-1])
    return out_x, out_y


