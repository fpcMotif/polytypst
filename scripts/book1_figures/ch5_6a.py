def _grouped_bar_svg(
    title: str,
    categories: Sequence[Sequence[str] | None],
    series: Sequence[tuple[str, str, Sequence[float | None]]],
    yticks: Sequence[float],
    group_labels: Sequence[tuple[str, int, int]],
    mode: ThemeMode,
    width: int = 560,
    height: int = 380,
) -> str:
    pal = get_palette(mode)
    label_rows = max(len(c) for c in categories if c)
    px0, px1 = 48.0, width - 14.0
    py0 = 38.0
    py1 = height - 30.0 - 14.0 * label_rows - (20.0 if group_labels else 0.0)
    ylo, yhi = yticks[0], yticks[-1]
    slot = (px1 - px0) / len(categories)
    bar_w = slot * 0.78 / len(series)

    def map_y(v: float) -> float:
        return py1 - (v - ylo) / (yhi - ylo) * (py1 - py0)

    def bar(x0: float, y0: float, w: float, h: float, style: str) -> list[str]:
        x1, y1 = x0 + w, y0 + h
        fill = pal.fills[3] if style == "dark" else pal.bg
        parts = [f'<rect x="{x0:.2f}" y="{y0:.2f}" width="{w:.2f}" height="{h:.2f}" fill="{fill}"/>']
        if style == "hatch":
            c = x0 - y1
            while c < x1 - y0:
                ya, yb = max(y0, x0 - c), min(y1, x1 - c)
                if ya < yb:
                    parts.append(
                        f'<line x1="{ya + c:.2f}" y1="{ya:.2f}" x2="{yb + c:.2f}" y2="{yb:.2f}" '
                        f'stroke="{pal.fg}" stroke-width="0.7"/>'
                    )
                c += 3.6
        elif style == "dots":
            row = 0
            yy = y0 + 1.8
            while yy < y1 - 0.8:
                xx = x0 + (1.6 if row % 2 == 0 else 4.0)
                while xx < x1 - 0.8:
                    parts.append(f'<circle cx="{xx:.2f}" cy="{yy:.2f}" r="0.6" fill="{pal.fg}"/>')
                    xx += 4.8
                yy += 2.6
                row += 1
        parts.append(
            f'<rect x="{x0:.2f}" y="{y0:.2f}" width="{w:.2f}" height="{h:.2f}" fill="none" stroke="{pal.fg}" stroke-width="0.8"/>'
        )
        return parts

    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}">',
        f"<title>{escape(title)}</title>",
        f'<rect width="{width}" height="{height}" fill="{pal.bg}"/>',
        f'<rect x="{px0:.2f}" y="{py0:.2f}" width="{px1 - px0:.2f}" height="{py1 - py0:.2f}" fill="{pal.panel_bg}" stroke="{pal.border}"/>',
    ]
    for v in yticks:
        yy = map_y(v)
        out.append(
            f'<line x1="{px0:.2f}" y1="{yy:.2f}" x2="{px1:.2f}" y2="{yy:.2f}" stroke="{pal.grid}" stroke-width="0.9" stroke-dasharray="2.5,2.5"/>'
        )
        out.append(f'<line x1="{px0:.2f}" y1="{yy:.2f}" x2="{px0 + 4.5:.2f}" y2="{yy:.2f}" stroke="{pal.axis}" stroke-width="1.1"/>')
        out.append(
            f'<text x="{px0 - 6.5:.2f}" y="{yy + 3.8:.2f}" text-anchor="end" font-family="{SANS_STACK}" '
            f'font-size="10.5" fill="{pal.muted}">{v:g}</text>'
        )
    for ci, cat in enumerate(categories):
        cx = px0 + slot * (ci + 0.5)
        if cat is None:
            continue
        for si, (_, style, values) in enumerate(series):
            v = values[ci]
            if v is None:
                continue
            bx = cx - bar_w * len(series) / 2 + bar_w * si
            out.extend(bar(bx, map_y(v), bar_w, map_y(ylo) - map_y(v), style))
        for li, line in enumerate(cat):
            out.append(
                f'<text x="{cx:.2f}" y="{py1 + 17.0 + 14.0 * li:.2f}" text-anchor="middle" font-family="{SANS_STACK}" '
                f'font-size="10.5" fill="{pal.fg}">{escape(line)}</text>'
            )
    for text, first, last in group_labels:
        gx = px0 + slot * ((first + last) / 2 + 0.5)
        out.append(
            f'<text x="{gx:.2f}" y="{py1 + 22.0 + 14.0 * label_rows:.2f}" text-anchor="middle" font-family="{FONT_STACK}" '
            f'font-size="11.5" fill="{pal.muted}">{escape(text)}</text>'
        )
    out.append(f'<rect x="{px0:.2f}" y="{py0:.2f}" width="{px1 - px0:.2f}" height="{py1 - py0:.2f}" fill="none" stroke="{pal.axis}" stroke-width="1.2"/>')
    item_w = [22.0 + 10.8 * 0.56 * len(label) + 14.0 for label, _, _ in series]
    lx = px0 + ((px1 - px0) - sum(item_w)) / 2
    for (label, style, _), iw in zip(series, item_w):
        out.extend(bar(lx, py0 - 18.5, 14.0, 9.0, style))
        out.append(
            f'<text x="{lx + 18:.2f}" y="{py0 - 10:.2f}" font-family="{FONT_STACK}" font-size="10.8" fill="{pal.fg}">{escape(label)}</text>'
        )
        lx += iw
    out.append("</svg>")
    return "\n".join(out)


