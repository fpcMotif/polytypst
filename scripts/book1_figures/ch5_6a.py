def _year_ticks(first: int, last: int, every: int = 2) -> list[float | tuple[float, str]]:
    return [(float(y), str(y)) for y in range(first, last + 1, every)]


def _spans(pairs: Sequence[tuple[float, float]]) -> list[VSpan]:
    return [VSpan(x0=a, x1=b, color_idx=0) for a, b in pairs]


def _xy(pts: Sequence[tuple[float, float]]) -> tuple[list[float], list[float]]:
    return [p[0] for p in pts], [p[1] for p in pts]


def _signed(values: Sequence[float], digits: int = 0) -> list[float | tuple[float, str]]:
    return [(v, f"{v:.{digits}f}".replace("-", "−")) for v in values]


