def _years(a: int, b: int) -> list[float]:
    return [float(y) for y in range(a, b + 1)]


def _dots(
    xs: list[float], ys: list[float | None], marker: str, idx: int = 0
) -> LineSeries:
    return LineSeries(
        x=[x for x in xs for _ in (0, 1)],
        y=[v for y in ys for v in (y, None)],
        color_idx=idx,
        marker=marker,
    )


