def _ticks(lo: float, hi: float, step: float) -> list[tuple[float, str]]:
    count = round((hi - lo) / step)
    digits = len(f"{step:g}".partition(".")[2])
    values = [round(lo + i * step, 4) + 0.0 for i in range(count + 1)]
    return [(v, f"{v:.{digits}f}") for v in values]


def _irf_figure(
    fig_id: str,
    caption: str,
    rows: Sequence[str],
    data: Sequence[Sequence[Sequence[float | None]]],
    ylims: Sequence[tuple[float, float, float]],
    mode: ThemeMode,
) -> str:
    panels = []
    for idx, (upper, estimate, lower) in enumerate(data):
        row, col = divmod(idx, 2)
        lo, hi, step = ylims[row]
        panels.append(
            PanelSpec(
                title=f"{rows[row]}（{_IRF_PERIODS[col]}）",
                xlim=(0.0, 20.0),
                ylim=(lo, hi),
                xticks=[0.0, 5.0, 10.0, 15.0, 20.0],
                yticks=_ticks(lo, hi, step),
                xlabel="发生冲击的季度后" if row == 2 else "",
                ylabel="万日元",
                lines=[
                    LineSeries(
                        x=_IRF_X,
                        y=estimate,
                        label="点估算值",
                        color_idx=0,
                        style="solid",
                        width=2.2,
                    ),
                    LineSeries(
                        x=_IRF_X,
                        y=upper,
                        label="+1个标准误差",
                        color_idx=1,
                        style="dashed",
                        width=1.6,
                    ),
                    LineSeries(
                        x=_IRF_X,
                        y=lower,
                        label="−1个标准误差",
                        color_idx=3,
                        style="dashed",
                        width=1.6,
                    ),
                ],
                legend_loc="none",
            )
        )
    spec = FigureSpec(
        fig_id=fig_id,
        title=f"图 {fig_id} {caption}",
        panels=panels,
        rows=3,
        cols=2,
        width=860,
        height=980,
    )
    return render_figure_svg(spec, mode)


def _series_panel(
    title: str,
    x: Sequence[float | None],
    y: Sequence[float | None],
    xlim: tuple[float, float],
    xticks: Sequence[float],
    ylim: tuple[float, float],
    ystep: float,
    ylabel: str,
    width: float = 1.6,
) -> PanelSpec:
    return PanelSpec(
        title=title,
        xlim=xlim,
        ylim=ylim,
        xticks=xticks,
        yticks=_ticks(ylim[0], ylim[1], ystep),
        xlabel="年",
        ylabel=ylabel,
        zero_line=ylim[0] < 0 < ylim[1],
        lines=[
            LineSeries(x=x, y=y, label=title, color_idx=0, style="solid", width=width)
        ],
        legend_loc="none",
    )


