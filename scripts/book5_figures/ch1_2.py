def _stacked(parts: list[list[float]]) -> list[list[float]]:
    """Bottoms for bars stacked in order: positive parts pile up from zero, negative parts pile down."""
    bottoms: list[list[float]] = []
    up = [0.0] * len(parts[0])
    down = [0.0] * len(parts[0])
    for part in parts:
        bottom: list[float] = []
        for i, v in enumerate(part):
            if v >= 0:
                bottom.append(up[i])
                up[i] += v
            else:
                bottom.append(down[i])
                down[i] += v
        bottoms.append(bottom)
    return bottoms


