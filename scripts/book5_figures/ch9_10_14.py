def _quantile_panel(
    title: str, points: list[tuple[float, float, float, float]]
) -> PanelSpec:
    x, upper, median, lower = (list(col) for col in zip(*points))
    return PanelSpec(
        title=title,
        xlim=(1986.0, 2008.0),
        ylim=(20.0, 140.0),
        xticks=[float(y) for y in range(1986, 2007, 4)],
        yticks=[20.0 * i for i in range(1, 8)],
        xlabel="年",
        zero_line=False,
        lines=[
            LineSeries(
                x=x, y=median, label="Median", color_idx=0, style="solid", width=1.8
            ),
            LineSeries(
                x=x,
                y=upper,
                label="0.25.0.75 Quantiles",
                color_idx=2,
                style="dashed",
                width=1.4,
            ),
            LineSeries(x=x, y=lower, color_idx=2, style="dashed", width=1.4),
        ],
        legend_loc="top",
    )


