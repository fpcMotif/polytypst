def _case_panel(
    title: str,
    ylim: tuple[float, float],
    yticks: list[float],
    case1: list[tuple[float, float]],
    case2: list[tuple[float, float]],
    legend: bool,
) -> PanelSpec:
    return PanelSpec(
        title=title,
        xlim=(-10.5, 100.5),
        ylim=ylim,
        xticks=[float(x) for x in range(-10, 91, 10)],
        yticks=yticks,
        ylabel="%",
        lines=[
            LineSeries(
                x=[p[0] for p in case1],
                y=[p[1] for p in case1],
                label="情况1",
                color_idx=0,
                style="solid",
                width=2.2,
            ),
            LineSeries(
                x=[p[0] for p in case2],
                y=[p[1] for p in case2],
                label="情况2",
                color_idx=1,
                style="dashed",
                width=2.2,
            ),
        ],
        legend_loc="bottom" if legend else "none",
    )


