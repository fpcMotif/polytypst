MONO_LIGHT_TO_DARK = (4, 2, 1, 5, 3, 0)


def _stack(
    x: list[float],
    layers: list[tuple[str, list[float]]],
    width: float = 0.6,
    shades: tuple[int, ...] = MONO_LIGHT_TO_DARK,
) -> list[BarSeries]:
    """Stack positive layers bottom to top, each starting where the one below ends."""
    base = [0.0] * len(x)
    bars = []
    for (label, ys), shade in zip(layers, shades):
        bars.append(
            BarSeries(
                x=x, y=ys, bottom=list(base), label=label, color_idx=shade, width=width
            )
        )
        base = [b + v for b, v in zip(base, ys)]
    return bars


