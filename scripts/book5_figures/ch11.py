FY70_TICKS = [float(y) for y in range(1970, 2005, 2)]
FY80_TICKS = [float(y) for y in range(1980, 2005, 2)]
FY70_LIM = (1969.5, 2004.5)
FY80_LIM = (1979.5, 2004.5)


def _years(first: int, last: int) -> list[float]:
    return [float(y) for y in range(first, last + 1)]


def _label(x: float, y: float, text: str) -> Annotation:
    return Annotation(x=x, y=y, text=text, dx=0.0, dy=0.0, arrow=False)


def _stacked_bars(
    years: Sequence[float], parts: Sequence[tuple[str, int, Sequence[float]]]
) -> list[BarSeries]:
    """Stack each part's positive values up from zero and its negative values down from zero."""
    pos = [0.0] * len(years)
    neg = [0.0] * len(years)
    bars: list[BarSeries] = []
    for label, color_idx, values in parts:
        bottoms = [pos[i] if v >= 0 else neg[i] for i, v in enumerate(values)]
        for i, v in enumerate(values):
            if v >= 0:
                pos[i] += v
            else:
                neg[i] += v
        bars.append(
            BarSeries(
                x=years,
                y=values,
                bottom=bottoms,
                label=label,
                color_idx=color_idx,
                width=0.7,
            )
        )
    return bars


def _total_line(years: Sequence[float], totals: Sequence[float]) -> LineSeries:
    return LineSeries(x=years, y=totals, color_idx=1, marker="circle", width=1.3)


def _two_lines(
    fig_id: str,
    title: str,
    years: Sequence[float],
    first: tuple[str, Sequence[float | None]],
    second: tuple[str, Sequence[float | None]],
    ylim: tuple[float, float],
    yticks: Sequence[float],
    *,
    ylabel: str = "",
    xlim: tuple[float, float] = FY70_LIM,
    xticks: Sequence[float] = FY70_TICKS,
    labels: Sequence[Annotation] = (),
    legend: bool = True,
) -> FigureSpec:
    """A panel of two fiscal-year lines: the first light (dashed in print), the second dark and solid."""
    panel = PanelSpec(
        xlim=xlim,
        ylim=ylim,
        xticks=xticks,
        yticks=yticks,
        xlabel="财年",
        ylabel=ylabel,
        lines=[
            LineSeries(
                x=years,
                y=first[1],
                label=first[0] if legend else "",
                color_idx=1,
                width=2.0,
            ),
            LineSeries(
                x=years,
                y=second[1],
                label=second[0] if legend else "",
                color_idx=0,
                width=2.0,
            ),
        ],
        annotations=labels,
        legend_loc="bottom" if legend else "none",
    )
    return FigureSpec(fig_id=fig_id, title=title, panels=[panel])


